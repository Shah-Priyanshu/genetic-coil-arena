"""R18: golden test vectors for the int8 swarm brains on the ESP32-S3 bench.

Parses ``hardware/esp32/swarm_brains_int8.h``, runs its documented integer recipe in
Python on seeded random feature vectors, and writes the quantised inputs and the final
int32 accumulators to ``hardware/esp32/bench/include/golden.h``. The bench firmware's
``brain`` command recomputes them on the chip and reports how many match exactly.

python scripts/r18_bench_golden.py [--n 32] [--seed 18]
"""

import argparse
import re
from pathlib import Path

import numpy as np

HEADER = Path("hardware/esp32/swarm_brains_int8.h")
OUT = Path("hardware/esp32/bench/include/golden.h")


def arrays(text: str) -> dict[str, np.ndarray]:
    out = {}
    for name, body in re.findall(
        r"static const \w+ (\w+)\[[^=]*=\s*(\{.*?\});", text, re.S
    ):
        out[name] = np.array(
            [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?(?:e-?\d+)?", body)]
        )
    for name, value in re.findall(r"static const float (\w+) = ([^f;]+)f;", text):
        out[name] = np.array(float(value))
    return out


def forward(a: dict[str, np.ndarray], brain: str, q: np.ndarray) -> np.ndarray:
    w0 = a[f"{brain}_w0"].reshape(15, 16)
    w1 = a[f"{brain}_w1"].reshape(16, 1)
    acc = q @ w0 + a[f"{brain}_b0"]
    h = np.clip(np.round(np.tanh(acc * float(a[f"{brain}_scale0"])) * 127), -127, 127)
    return (h @ w1 + a[f"{brain}_b1"])[:, 0].astype(np.int64)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--n", type=int, default=32)
    p.add_argument("--seed", type=int, default=18)
    args = p.parse_args()
    a = arrays(HEADER.read_text(encoding="utf-8"))
    x = np.random.default_rng(args.seed).uniform(-1.5, 1.5, size=(args.n, 15))
    q = np.clip(np.round(x * 64), -128, 127)
    rows = ",\n".join("  {" + ", ".join(str(int(v)) for v in r) + "}" for r in q)
    lines = [
        "// Golden vectors for the bench's brain check. Generated by",
        "// scripts/r18_bench_golden.py from swarm_brains_int8.h; do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        f"#define GOLDEN_N {args.n}",
        f"static const int8_t golden_x[GOLDEN_N][15] = {{\n{rows}\n}};",
    ]
    for brain in ("gas", "cam"):
        vals = ", ".join(str(int(v)) for v in forward(a, brain, q))
        lines.append(f"static const int32_t golden_{brain}[GOLDEN_N] = {{{vals}}};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{args.n} golden vectors -> {OUT}")


if __name__ == "__main__":
    main()
